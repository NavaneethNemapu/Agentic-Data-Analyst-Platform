import json
import math
import os
import re
import time
from typing import Any

class ExperienceBank:
    """
    Analyst Experience Replay (AER) Memory:
    Autonomous vector-indexed experience store that remembers verified SQL patterns
    and dynamically injects them as few-shot exemplars into agent prompts.
    
    Student Original Contribution: Self-improving text-to-SQL through verified analytical memory.
    """
    def __init__(self, storage_path: str = "data/experience_memory.json", dim: int = 256):
        self.storage_path = storage_path
        self.dim = dim
        self.experiences: list[dict[str, Any]] = []
        self._load_or_seed()

    def _text_to_vector(self, text: str) -> list[float]:
        vec = [0.0] * self.dim
        tokens = re.findall(r'[a-zA-Z0-9_]+', text.lower())
        for token in tokens:
            h = abs(hash(token)) % self.dim
            vec[h] += 1.0
            for i in range(len(token) - 2):
                ngram = token[i:i+3]
                h_ng = abs(hash(ngram)) % self.dim
                vec[h_ng] += 0.5
        norm = math.sqrt(sum(x * x for x in vec))
        return [x / norm for x in vec] if norm > 0 else vec

    def _cosine_similarity(self, v1: list[float], v2: list[float]) -> float:
        if not v1 or not v2:
            return 0.0
        return sum(a * b for a, b in zip(v1, v2))

    def _load_or_seed(self):
        os.makedirs(os.path.dirname(self.storage_path), exist_ok=True)
        if os.path.exists(self.storage_path):
            try:
                with open(self.storage_path, "r", encoding="utf-8") as f:
                    self.experiences = json.load(f)
                    return
            except Exception:
                self.experiences = []
        
        # Seed with initial verified golden patterns
        self.experiences = [
            {
                "question": "Calculate the net profit generated by each product",
                "sql": "SELECT p.name, ROUND(SUM(oi.quantity * (oi.unit_price - p.cost)), 2) AS net_profit FROM order_items oi JOIN products p ON oi.product_id = p.product_id GROUP BY p.name ORDER BY net_profit DESC;",
                "strategy": "multi_table_profit_margin",
                "created_at": time.time()
            },
            {
                "question": "Find high-value customers who spent more than 5000 on completed orders",
                "sql": "SELECT c.first_name, c.last_name, ROUND(SUM(oi.quantity * oi.unit_price), 2) AS total_spent FROM customers c JOIN orders o ON c.customer_id = o.customer_id JOIN order_items oi ON o.order_id = oi.order_id WHERE LOWER(o.status) = 'completed' GROUP BY c.customer_id, c.first_name, c.last_name HAVING total_spent > 5000 ORDER BY total_spent DESC;",
                "strategy": "case_insensitive_status_filter_with_having",
                "created_at": time.time()
            },
            {
                "question": "What is the average order value for customers in each country",
                "sql": "WITH order_totals AS (SELECT o.order_id, c.country, SUM(oi.quantity * oi.unit_price) AS order_total FROM orders o JOIN customers c ON o.customer_id = c.customer_id JOIN order_items oi ON o.order_id = oi.order_id GROUP BY o.order_id, c.country) SELECT country, ROUND(AVG(order_total), 2) AS average_order_value FROM order_totals GROUP BY country ORDER BY average_order_value DESC;",
                "strategy": "cte_subquery_aggregation",
                "created_at": time.time()
            }
        ]
        self._save()

    def _save(self):
        try:
            with open(self.storage_path, "w", encoding="utf-8") as f:
                json.dump(self.experiences, f, indent=2)
        except Exception as e:
            print(f"[ExperienceBank] Failed to persist memory: {e}")

    def find_similar_exemplars(self, question: str, threshold: float = 0.40, top_k: int = 2) -> list[dict[str, Any]]:
        """
        Retrieve nearest verified analytical memories using cosine semantic similarity.
        """
        if not self.experiences:
            return []
        
        q_vec = self._text_to_vector(question)
        scored = []
        for exp in self.experiences:
            exp_vec = self._text_to_vector(exp["question"])
            sim = self._cosine_similarity(q_vec, exp_vec)
            if sim >= threshold:
                scored.append((sim, exp))
        
        scored.sort(key=lambda x: x[0], reverse=True)
        return [
            {
                "question": item["question"],
                "sql": item["sql"],
                "strategy": item.get("strategy", "verified_query"),
                "similarity": round(score, 3)
            }
            for score, item in scored[:top_k]
        ]

    def record_experience(self, question: str, sql: str, strategy: str = "validated_execution"):
        """
        Record a newly validated query so the system learns from its successes.
        """
        clean_q = question.strip()
        clean_sql = sql.strip()
        
        # Avoid duplicate recordings
        for exp in self.experiences:
            if exp["question"].lower() == clean_q.lower():
                return
                
        self.experiences.append({
            "question": clean_q,
            "sql": clean_sql,
            "strategy": strategy,
            "created_at": time.time()
        })
        self._save()

experience_bank = ExperienceBank()
